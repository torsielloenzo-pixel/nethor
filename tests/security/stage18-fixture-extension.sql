ALTER TABLE public.chat_participants
  ADD COLUMN last_read_at timestamptz,
  ADD COLUMN muted boolean NOT NULL DEFAULT false;

CREATE TABLE public.notification_rules(
  key text PRIMARY KEY,
  label text,
  description text,
  trigger_text text,
  enabled boolean,
  push_allowed boolean,
  portal_enabled boolean,
  push_enabled boolean,
  sort_order integer
);
CREATE TABLE public.notification_controls(
  user_id uuid PRIMARY KEY REFERENCES public.profiles(id),
  enabled boolean
);
CREATE TABLE public.push_subscriptions(
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid REFERENCES public.profiles(id)
);
CREATE TABLE public.chat_conversations(
  id uuid PRIMARY KEY,
  type text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  archived_at timestamptz
);
CREATE TABLE public.chat_messages(
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id uuid REFERENCES public.chat_conversations(id),
  deleted_at timestamptz
);
CREATE TABLE public.chat_presence_history(
  user_id uuid PRIMARY KEY REFERENCES public.profiles(id),
  online_since timestamptz,
  last_seen_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  last_session_seconds bigint NOT NULL DEFAULT 0,
  total_online_seconds bigint NOT NULL DEFAULT 0
);
CREATE TABLE public.chat_user_conversation_state(
  user_id uuid REFERENCES public.profiles(id),
  conversation_id uuid REFERENCES public.chat_conversations(id),
  archived_at timestamptz,
  hidden_at timestamptz,
  updated_at timestamptz,
  PRIMARY KEY(user_id,conversation_id)
);
CREATE TABLE public.user_subroles(
  user_id uuid REFERENCES public.profiles(id),
  subrole_key text NOT NULL,
  PRIMARY KEY(user_id,subrole_key)
);
CREATE TABLE public.subrole_module_permissions(
  subrole_key text NOT NULL,
  module text NOT NULL,
  permission text NOT NULL,
  PRIMARY KEY(subrole_key,module)
);
CREATE TABLE public.weekly_polls(
  id uuid PRIMARY KEY,
  end_on date NOT NULL
);
CREATE TABLE public.weekly_poll_options(
  id uuid PRIMARY KEY,
  poll_id uuid NOT NULL REFERENCES public.weekly_polls(id),
  position integer NOT NULL
);
CREATE TABLE public.weekly_poll_votes(
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  poll_id uuid NOT NULL REFERENCES public.weekly_polls(id),
  option_id uuid NOT NULL REFERENCES public.weekly_poll_options(id)
);

